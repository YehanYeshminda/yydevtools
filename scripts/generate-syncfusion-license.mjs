/**
 * Writes the Syncfusion client license key into a TypeScript constant, from
 * the SYNCFUSION_LICENSE_KEY environment variable.
 *
 * Every other piece of configuration in this repo either lives server-side in
 * the Worker (never reaching the browser) or, for the three Fly services, is a
 * secret guarded behind an Authorization header. This is the first value that
 * has to ship *inside* the client bundle by design — Syncfusion's licensing
 * model works by validating a token the browser itself presents, so there is
 * no way to keep it off the client (`word-viewer.ts` registers it before the
 * Document Editor renders). What this script avoids is committing that token
 * as a literal in source: the generated file is gitignored, and a placeholder
 * ships in its place so a fresh checkout still builds — without a real key the
 * editor runs in Syncfusion's own trial mode rather than failing outright,
 * which is why an empty string is a safe fallback rather than a build error.
 *
 * Runs before `ng build`/`ng serve`/`ng build --watch` — see the "prebuild",
 * "prestart" and "prewatch" scripts in package.json.
 *
 * Falls back to reading `.env.local` (also gitignored — see .gitignore's
 * `.env*` entry) if the environment variable itself isn't set, so the key
 * only has to be pasted once rather than exported in every shell that runs a
 * build.
 */
import { writeFile, readFile } from 'node:fs/promises';

const OUT_FILE = 'src/app/tools/word-viewer/syncfusion-license.generated.ts';

async function readEnvLocal(name) {
  try {
    const text = await readFile('.env.local', 'utf8');
    for (const line of text.split('\n')) {
      const trimmed = line.trim();
      if (trimmed.startsWith('#') || !trimmed.includes('=')) {
        continue;
      }
      const [key, ...rest] = trimmed.split('=');
      if (key.trim() === name) {
        return rest.join('=').trim();
      }
    }
  } catch {
    // No .env.local — fine, the caller falls back to an empty key.
  }
  return undefined;
}

const key = process.env.SYNCFUSION_LICENSE_KEY ?? (await readEnvLocal('SYNCFUSION_LICENSE_KEY')) ?? '';

const contents = `// Generated by scripts/generate-syncfusion-license.mjs — do not edit by hand,
// and do not commit a real key here. Set SYNCFUSION_LICENSE_KEY in the
// environment before building; an empty string leaves the Document Editor in
// Syncfusion's trial mode instead of failing the build.
export const SYNCFUSION_LICENSE_KEY = ${JSON.stringify(key)};
`;

await writeFile(OUT_FILE, contents);
console.log(
  key
    ? `Wrote ${OUT_FILE} (license key set, ${key.length} chars).`
    : `Wrote ${OUT_FILE} (no SYNCFUSION_LICENSE_KEY set — Document Editor will run in trial mode).`,
);
